begin;

create table if not exists public.platform_connections (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  provider text not null check (provider in ('github', 'vercel', 'netlify', 'render')),
  external_account_id text not null,
  external_account_name text,
  installation_id bigint,
  status text not null default 'connected' check (status in ('pending', 'connected', 'disconnected', 'error')),
  scopes text[] not null default '{}',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, provider, external_account_id)
);

create unique index if not exists platform_connections_provider_installation_uidx
  on public.platform_connections(provider, installation_id)
  where installation_id is not null;

create index if not exists platform_connections_workspace_provider_idx
  on public.platform_connections(workspace_id, provider, status);

create table if not exists public.platform_projects (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  platform_connection_id uuid not null references public.platform_connections(id) on delete cascade,
  provider text not null check (provider in ('github', 'vercel', 'netlify', 'render')),
  external_project_id text not null,
  name text not null,
  full_name text,
  repository_url text,
  dashboard_url text,
  default_branch text,
  metadata jsonb not null default '{}'::jsonb,
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, provider, external_project_id)
);

create index if not exists platform_projects_workspace_provider_idx
  on public.platform_projects(workspace_id, provider);

create table if not exists public.website_installations (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  website_connection_id uuid not null references public.website_connections(id) on delete cascade,
  platform_project_id uuid references public.platform_projects(id) on delete set null,
  provider text not null check (provider in ('github', 'vercel', 'netlify', 'render')),
  deployment_mode text not null default 'manual' check (deployment_mode in ('automatic', 'manual')),
  status text not null default 'prepared' check (status in ('prepared', 'awaiting_approval', 'auto_merge_enabled', 'deploying', 'deployed', 'verified', 'failed', 'removed')),
  branch_name text,
  target_branch text,
  file_path text,
  pull_request_number integer,
  pull_request_url text,
  dashboard_url text,
  deployed_url text,
  last_verified_at timestamptz,
  deployed_at timestamptz,
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists website_installations_workspace_created_idx
  on public.website_installations(workspace_id, created_at desc);
create index if not exists website_installations_website_idx
  on public.website_installations(website_connection_id, created_at desc);

create table if not exists public.platform_installation_logs (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  installation_id uuid references public.website_installations(id) on delete set null,
  provider text not null check (provider in ('github', 'vercel', 'netlify', 'render')),
  level text not null default 'info' check (level in ('info', 'warning', 'error')),
  event text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists platform_installation_logs_workspace_created_idx
  on public.platform_installation_logs(workspace_id, created_at desc);

-- Short-lived, one-time state values for provider callbacks. No browser access.
create table if not exists public.platform_oauth_states (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null check (provider in ('github', 'vercel', 'netlify', 'render')),
  state_hash text not null unique,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.platform_connections enable row level security;
alter table public.platform_projects enable row level security;
alter table public.website_installations enable row level security;
alter table public.platform_installation_logs enable row level security;
alter table public.platform_oauth_states enable row level security;

drop policy if exists platform_connections_member_read on public.platform_connections;
create policy platform_connections_member_read on public.platform_connections
  for select to authenticated using (public.is_workspace_member(workspace_id));

drop policy if exists platform_projects_member_read on public.platform_projects;
create policy platform_projects_member_read on public.platform_projects
  for select to authenticated using (public.is_workspace_member(workspace_id));

drop policy if exists website_installations_member_read on public.website_installations;
create policy website_installations_member_read on public.website_installations
  for select to authenticated using (public.is_workspace_member(workspace_id));

drop policy if exists platform_installation_logs_member_read on public.platform_installation_logs;
create policy platform_installation_logs_member_read on public.platform_installation_logs
  for select to authenticated using (public.is_workspace_member(workspace_id));

-- OAuth state and all provider writes are service-role-only.
revoke all on public.platform_oauth_states from anon, authenticated;
revoke insert, update, delete on public.platform_connections from anon, authenticated;
revoke insert, update, delete on public.platform_projects from anon, authenticated;
revoke insert, update, delete on public.website_installations from anon, authenticated;
revoke insert, update, delete on public.platform_installation_logs from anon, authenticated;

grant select on public.platform_connections to authenticated;
grant select on public.platform_projects to authenticated;
grant select on public.website_installations to authenticated;
grant select on public.platform_installation_logs to authenticated;

commit;
