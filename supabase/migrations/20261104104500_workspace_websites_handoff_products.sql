create table if not exists public.workspace_websites (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null default 'Website',
  website_url text not null,
  domain text not null,
  public_key uuid not null default gen_random_uuid() unique,
  status text not null default 'pending' check (status in ('pending','connected','paused')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, domain)
);

alter table public.conversations add column if not exists website_id uuid references public.workspace_websites(id) on delete set null;
alter table public.conversations add column if not exists visitor_session_id text;
create index if not exists workspace_websites_workspace_idx on public.workspace_websites(workspace_id, created_at desc);
create index if not exists conversations_website_updated_idx on public.conversations(website_id, updated_at desc);
create unique index if not exists conversations_website_session_unique on public.conversations(website_id, visitor_session_id)
  where website_id is not null and visitor_session_id is not null;

create table if not exists public.human_handoff_requests (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  website_id uuid references public.workspace_websites(id) on delete set null,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  visitor_name text not null default 'Website visitor',
  visitor_email text,
  request_note text,
  status text not null default 'open' check (status in ('open','assigned','resolved')),
  read_at timestamptz,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);
create index if not exists human_handoff_workspace_created_idx on public.human_handoff_requests(workspace_id, created_at desc);
create index if not exists human_handoff_conversation_idx on public.human_handoff_requests(conversation_id, created_at desc);
create unique index if not exists human_handoff_one_open_per_conversation on public.human_handoff_requests(conversation_id)
  where status in ('open','assigned');

create table if not exists public.workspace_products (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  kind text not null check (kind in ('product','service')),
  name text not null,
  description text not null default '',
  price numeric(12,2),
  currency text not null default 'RWF',
  status text not null default 'draft' check (status in ('draft','active','archived')),
  source text not null default 'manual' check (source in ('manual','visitor_request','website_review','ai_advice')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists workspace_products_workspace_idx on public.workspace_products(workspace_id, created_at desc);

create table if not exists public.website_scan_runs (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  website_id uuid not null references public.workspace_websites(id) on delete cascade,
  status text not null default 'queued' check (status in ('queued','scanning','completed','failed')),
  pages_scanned integer not null default 0,
  summary text,
  error text,
  started_at timestamptz not null default now(),
  completed_at timestamptz
);
create index if not exists website_scan_workspace_idx on public.website_scan_runs(workspace_id, started_at desc);

alter table public.workspace_websites enable row level security;
alter table public.human_handoff_requests enable row level security;
alter table public.workspace_products enable row level security;
alter table public.website_scan_runs enable row level security;

drop policy if exists workspace_websites_member_access on public.workspace_websites;
create policy workspace_websites_member_access on public.workspace_websites for all to authenticated
  using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
drop policy if exists human_handoff_member_access on public.human_handoff_requests;
create policy human_handoff_member_access on public.human_handoff_requests for all to authenticated
  using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
drop policy if exists workspace_products_member_access on public.workspace_products;
create policy workspace_products_member_access on public.workspace_products for all to authenticated
  using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
drop policy if exists website_scan_runs_member_access on public.website_scan_runs;
create policy website_scan_runs_member_access on public.website_scan_runs for all to authenticated
  using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));

grant select, insert, update, delete on public.workspace_websites to authenticated;
grant select, insert, update, delete on public.human_handoff_requests to authenticated;
grant select, insert, update, delete on public.workspace_products to authenticated;
grant select, insert, update, delete on public.website_scan_runs to authenticated;
grant usage, select on sequence public.human_handoff_requests_id_seq to authenticated;
grant usage, select on sequence public.workspace_products_id_seq to authenticated;
