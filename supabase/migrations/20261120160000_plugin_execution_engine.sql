begin;

create table if not exists public.plugin_execution_jobs (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id bigint references public.conversations(id) on delete set null,
  provider text not null check (provider in ('github', 'vercel', 'render', 'netlify')),
  operation text not null check (operation in ('widget_install', 'deployment')),
  status text not null check (status in (
    'pending','planning','awaiting_website','awaiting_repository','awaiting_approval',
    'approved','executing','awaiting_merge','deploying','verifying','completed','failed','cancelled'
  )),
  request_text text not null check (char_length(request_text) <= 4000),
  repository_id bigint,
  repository_full_name text,
  repository_url text,
  default_branch text,
  branch_name text,
  file_path text,
  pull_request_number integer,
  pull_request_url text,
  plan jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  approved_by uuid references auth.users(id) on delete set null,
  approved_at timestamptz,
  expires_at timestamptz not null default (now() + interval '7 days'),
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists plugin_execution_jobs_workspace_created_idx
  on public.plugin_execution_jobs(workspace_id, created_at desc);
create index if not exists plugin_execution_jobs_conversation_status_idx
  on public.plugin_execution_jobs(workspace_id, conversation_id, status, created_at desc);
create unique index if not exists plugin_execution_jobs_one_open_conversation_idx
  on public.plugin_execution_jobs(workspace_id, conversation_id)
  where conversation_id is not null and status in (
    'pending','planning','awaiting_website','awaiting_repository','awaiting_approval',
    'approved','executing','awaiting_merge','deploying','verifying'
  );

create table if not exists public.plugin_execution_steps (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  job_id uuid not null references public.plugin_execution_jobs(id) on delete cascade,
  step_key text not null,
  status text not null default 'pending' check (status in ('pending','running','succeeded','failed','skipped')),
  input_summary jsonb not null default '{}'::jsonb,
  output_summary jsonb not null default '{}'::jsonb,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  error_message text,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(job_id, step_key)
);

create table if not exists public.plugin_execution_approvals (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  job_id uuid not null unique references public.plugin_execution_jobs(id) on delete cascade,
  approved_by uuid not null references auth.users(id) on delete restrict,
  decision text not null check (decision in ('approved','rejected')),
  approved_scope jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.plugin_execution_logs (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  job_id uuid references public.plugin_execution_jobs(id) on delete set null,
  actor_user_id uuid references auth.users(id) on delete set null,
  event text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists plugin_execution_logs_job_created_idx
  on public.plugin_execution_logs(job_id, created_at desc);

create table if not exists public.repository_installations (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  github_connection_id uuid not null references public.platform_connections(id) on delete cascade,
  website_connection_id uuid not null references public.website_connections(id) on delete cascade,
  repository_id bigint not null,
  repository_full_name text not null,
  framework text not null,
  adapter text not null,
  entrypoint text not null,
  status text not null default 'pending' check (status in ('pending','installed','removed','failed')),
  branch_name text,
  commit_sha text,
  pull_request_number integer,
  pull_request_url text,
  installed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(workspace_id, website_connection_id, repository_id)
);

create table if not exists public.hosting_project_connections (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  platform_project_id uuid not null references public.platform_projects(id) on delete cascade,
  provider text not null check (provider in ('vercel','render','netlify')),
  repository_full_name text,
  deploy_strategy text not null default 'provider_auto' check (deploy_strategy in ('provider_auto','manual')),
  status text not null default 'linked' check (status in ('linked','paused','disconnected','error')),
  last_checked_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(platform_project_id)
);
create index if not exists hosting_project_connections_repository_idx
  on public.hosting_project_connections(workspace_id, repository_full_name, provider);

create table if not exists public.deployment_records (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  job_id uuid references public.plugin_execution_jobs(id) on delete set null,
  hosting_project_connection_id uuid references public.hosting_project_connections(id) on delete set null,
  provider text not null check (provider in ('vercel','render','netlify')),
  external_deployment_id text,
  commit_sha text,
  status text not null default 'queued' check (status in ('queued','building','live','failed','verifying','verified','cancelled')),
  deployment_url text,
  health_status text not null default 'pending' check (health_status in ('pending','healthy','unhealthy','unknown')),
  health_checked_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists deployment_records_workspace_created_idx
  on public.deployment_records(workspace_id, created_at desc);
create index if not exists deployment_records_job_idx
  on public.deployment_records(job_id, created_at desc);

-- Execution plans can contain source-code context. Keep all execution tables
-- inaccessible to browser roles; authenticated callers use the Edge Function.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'plugin_execution_jobs','plugin_execution_steps','plugin_execution_approvals',
    'plugin_execution_logs','repository_installations','hosting_project_connections',
    'deployment_records'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on public.%I from public, anon, authenticated', table_name);
    execute format('grant all on public.%I to service_role', table_name);
  end loop;
end
$$;

grant usage, select on sequence public.plugin_execution_logs_id_seq to service_role;

commit;
