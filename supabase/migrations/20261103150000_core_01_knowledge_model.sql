create or replace function public.misma_replace_latest_response(
  p_conversation_id bigint,
  p_user_message_id bigint,
  p_answer text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_workspace_id uuid;
  v_latest_user_message_id bigint;
  v_message public.messages%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_answer is null or length(trim(p_answer)) = 0 or length(p_answer) > 8000 then
    raise exception 'Invalid response text' using errcode = '22023';
  end if;

  select c.workspace_id into v_workspace_id
  from public.conversations c
  where c.id = p_conversation_id
  for update;

  if v_workspace_id is null or not exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = v_workspace_id and wm.user_id = auth.uid()
  ) then
    raise exception 'Conversation not found or access denied' using errcode = '42501';
  end if;

  select m.id into v_latest_user_message_id
  from public.messages m
  where m.conversation_id = p_conversation_id
    and m.role in ('human','customer')
  order by m.id desc
  limit 1;

  if v_latest_user_message_id is distinct from p_user_message_id then
    raise exception 'A newer user message exists; refresh before regenerating' using errcode = '40001';
  end if;

  delete from public.messages
  where conversation_id = p_conversation_id and id > p_user_message_id;

  insert into public.messages (conversation_id, role, text, attachments)
  values (p_conversation_id, 'ai', p_answer, '[]'::jsonb)
  returning * into v_message;

  update public.conversations
  set latest_text = left(p_answer, 200), updated_at = now()
  where id = p_conversation_id and workspace_id = v_workspace_id;

  return jsonb_build_object(
    'id', v_message.id::text,
    'role', v_message.role,
    'text', v_message.text,
    'created_at', v_message.created_at,
    'attachments', coalesce(v_message.attachments, '[]'::jsonb)
  );
end;
$$;

revoke all on function public.misma_replace_latest_response(bigint,bigint,text) from public;
grant execute on function public.misma_replace_latest_response(bigint,bigint,text) to authenticated;

