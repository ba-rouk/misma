BEGIN;

CREATE TABLE public.workspaces (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL DEFAULT 'My Workspace',
  location text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  opening_hours text NOT NULL DEFAULT '',
  primary_language text NOT NULL DEFAULT 'English'
    CHECK (primary_language IN ('English', 'Kinyarwanda', 'French', 'Swahili')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.workspace_members (
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'owner' CHECK (role IN ('owner', 'admin', 'member')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (workspace_id, user_id),
  UNIQUE (user_id)
);

CREATE TABLE public.contacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  name text NOT NULL DEFAULT 'Customer',
  orders_count integer NOT NULL DEFAULT 0 CHECK (orders_count >= 0),
  lifetime_value_rwf bigint NOT NULL DEFAULT 0 CHECK (lifetime_value_rwf >= 0),
  last_interaction timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.conversations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  contact_id bigint REFERENCES public.contacts(id) ON DELETE SET NULL,
  channel text NOT NULL DEFAULT 'Dashboard',
  latest_text text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'AI' CHECK (status IN ('AI', 'Needs you', 'Closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('customer', 'ai', 'human', 'system')),
  text text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.orders (
  id text PRIMARY KEY DEFAULT ('ord_' || gen_random_uuid()::text),
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  contact_id bigint REFERENCES public.contacts(id) ON DELETE SET NULL,
  item text NOT NULL,
  total_rwf bigint NOT NULL DEFAULT 0 CHECK (total_rwf >= 0),
  status text NOT NULL DEFAULT 'New'
    CHECK (status IN ('New', 'Confirmed', 'Preparing', 'Delivered', 'Cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.knowledge_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  question text NOT NULL,
  answer text NOT NULL,
  approved boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  entity_id text,
  payload jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX contacts_workspace_value_idx
  ON public.contacts (workspace_id, lifetime_value_rwf DESC);
CREATE INDEX conversations_workspace_updated_idx
  ON public.conversations (workspace_id, updated_at DESC);
CREATE INDEX messages_conversation_created_idx
  ON public.messages (conversation_id, created_at);
CREATE INDEX orders_workspace_created_idx
  ON public.orders (workspace_id, created_at DESC);
CREATE INDEX knowledge_workspace_approved_idx
  ON public.knowledge_entries (workspace_id, approved, id DESC);
CREATE INDEX audit_events_workspace_created_idx
  ON public.audit_events (workspace_id, created_at DESC);

CREATE FUNCTION public.is_workspace_member(target_workspace_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.workspace_members AS member
    WHERE member.workspace_id = target_workspace_id
      AND member.user_id = (SELECT auth.uid())
  );
$function$;

CREATE FUNCTION public.can_manage_workspace(target_workspace_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public.workspace_members AS member
    WHERE member.workspace_id = target_workspace_id
      AND member.user_id = (SELECT auth.uid())
      AND member.role IN ('owner', 'admin')
  );
$function$;

CREATE FUNCTION public.create_misma_workspace()
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  current_user_id uuid := (SELECT auth.uid());
  new_workspace_id uuid;
BEGIN
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(current_user_id::text, 0));

  SELECT member.workspace_id
  INTO new_workspace_id
  FROM public.workspace_members AS member
  WHERE member.user_id = current_user_id
  LIMIT 1;

  IF new_workspace_id IS NOT NULL THEN
    RETURN new_workspace_id;
  END IF;

  INSERT INTO public.workspaces (owner_id)
  VALUES (current_user_id)
  RETURNING id INTO new_workspace_id;

  INSERT INTO public.workspace_members (workspace_id, user_id, role)
  VALUES (new_workspace_id, current_user_id, 'owner');

  RETURN new_workspace_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.is_workspace_member(uuid) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.can_manage_workspace(uuid) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.create_misma_workspace() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_workspace_member(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_manage_workspace(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.create_misma_workspace() TO authenticated;

ALTER TABLE public.workspaces ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workspace_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.knowledge_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_events ENABLE ROW LEVEL SECURITY;

CREATE POLICY workspace_members_read
  ON public.workspace_members FOR SELECT TO authenticated
  USING (
    user_id = (SELECT auth.uid())
    OR public.is_workspace_member(workspace_id)
  );

CREATE POLICY workspaces_read
  ON public.workspaces FOR SELECT TO authenticated
  USING (public.is_workspace_member(id));

CREATE POLICY workspaces_update
  ON public.workspaces FOR UPDATE TO authenticated
  USING (public.can_manage_workspace(id))
  WITH CHECK (public.can_manage_workspace(id));

CREATE POLICY contacts_member_access
  ON public.contacts FOR ALL TO authenticated
  USING (public.is_workspace_member(workspace_id))
  WITH CHECK (public.is_workspace_member(workspace_id));

CREATE POLICY conversations_member_access
  ON public.conversations FOR ALL TO authenticated
  USING (public.is_workspace_member(workspace_id))
  WITH CHECK (public.is_workspace_member(workspace_id));

CREATE POLICY messages_member_access
  ON public.messages FOR ALL TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.conversations AS conversation
      WHERE conversation.id = messages.conversation_id
        AND public.is_workspace_member(conversation.workspace_id)
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.conversations AS conversation
      WHERE conversation.id = messages.conversation_id
        AND public.is_workspace_member(conversation.workspace_id)
    )
  );

CREATE POLICY orders_member_access
  ON public.orders FOR ALL TO authenticated
  USING (public.is_workspace_member(workspace_id))
  WITH CHECK (public.is_workspace_member(workspace_id));

CREATE POLICY knowledge_member_access
  ON public.knowledge_entries FOR ALL TO authenticated
  USING (public.is_workspace_member(workspace_id))
  WITH CHECK (public.is_workspace_member(workspace_id));

CREATE POLICY audit_events_member_access
  ON public.audit_events FOR ALL TO authenticated
  USING (public.is_workspace_member(workspace_id))
  WITH CHECK (public.is_workspace_member(workspace_id));

CREATE OR REPLACE FUNCTION public.sync_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_workspaces_timestamp ON public.workspaces;
CREATE TRIGGER update_workspaces_timestamp 
BEFORE UPDATE ON public.workspaces 
FOR EACH ROW 
EXECUTE FUNCTION public.sync_updated_at();

DROP TRIGGER IF EXISTS update_conversations_timestamp ON public.conversations;
CREATE TRIGGER update_conversations_timestamp 
BEFORE UPDATE ON public.conversations 
FOR EACH ROW 
EXECUTE FUNCTION public.sync_updated_at();

COMMIT;
