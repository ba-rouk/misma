begin;

create table if not exists public.website_connections (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null,
  website_url text not null,
  domain text not null,
  public_key uuid not null default gen_random_uuid() unique,
  status text not null default 'pending' check (status in ('pending','connected','paused')),
  last_seen_at timestamptz,
  last_scanned_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, domain)
);

alter table public.contacts
  add column if not exists email text,
  add column if not exists phone text,
  add column if not exists visitor_id uuid,
  add column if not exists source text not null default 'workspace';

create unique index if not exists contacts_workspace_visitor_uidx
  on public.contacts(workspace_id, visitor_id);

alter table public.conversations
  add column if not exists website_connection_id uuid references public.website_connections(id) on delete set null,
  add column if not exists visitor_id uuid;

create index if not exists conversations_website_connection_idx
  on public.conversations(website_connection_id, updated_at desc)
  where website_connection_id is not null;

create table if not exists public.human_requests (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  contact_id bigint references public.contacts(id) on delete set null,
  visitor_name text not null default 'Website visitor',
  visitor_email text,
  visitor_phone text,
  reason text not null default 'Visitor requested a human agent',
  status text not null default 'pending' check (status in ('pending','handled','closed')),
  created_at timestamptz not null default now(),
  handled_at timestamptz
);

create index if not exists human_requests_workspace_status_idx
  on public.human_requests(workspace_id, status, created_at desc);
create unique index if not exists human_requests_one_open_per_conversation_uidx
  on public.human_requests(conversation_id) where status = 'pending';

create table if not exists public.workspace_notifications (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  notification_type text not null check (notification_type in ('visitor_message','human_request','website_connected','website_scan_completed')),
  title text not null,
  body text not null default '',
  conversation_id bigint references public.conversations(id) on delete set null,
  contact_id bigint references public.contacts(id) on delete set null,
  human_request_id bigint references public.human_requests(id) on delete set null,
  website_connection_id uuid references public.website_connections(id) on delete set null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists workspace_notifications_workspace_created_idx
  on public.workspace_notifications(workspace_id, created_at desc);
create index if not exists workspace_notifications_workspace_unread_idx
  on public.workspace_notifications(workspace_id, created_at desc) where is_read = false;

create table if not exists public.products_services (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  item_type text not null check (item_type in ('product','service')),
  name text not null,
  description text not null default '',
  price_text text not null default '',
  active boolean not null default true,
  created_from text not null default 'manual' check (created_from in ('manual','customer_demand','website_scan')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_services_workspace_active_idx
  on public.products_services(workspace_id, active, item_type, created_at desc);

create table if not exists public.website_scan_runs (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  website_connection_id uuid not null references public.website_connections(id) on delete cascade,
  status text not null default 'completed' check (status in ('running','completed','failed')),
  page_count integer not null default 0,
  summary text not null default '',
  suggested_knowledge jsonb not null default '[]'::jsonb,
  suggested_products jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.knowledge_entries
  add column if not exists source_type text not null default 'manual',
  add column if not exists source_ref text;

alter table public.website_connections enable row level security;
alter table public.human_requests enable row level security;
alter table public.workspace_notifications enable row level security;
alter table public.products_services enable row level security;
alter table public.website_scan_runs enable row level security;

drop policy if exists website_connections_member_access on public.website_connections;
create policy website_connections_member_access on public.website_connections
for all to authenticated using (public.is_workspace_member(workspace_id))
with check (public.is_workspace_member(workspace_id));

drop policy if exists human_requests_member_read on public.human_requests;
create policy human_requests_member_read on public.human_requests
for select to authenticated using (public.is_workspace_member(workspace_id));
drop policy if exists human_requests_member_update on public.human_requests;
create policy human_requests_member_update on public.human_requests
for update to authenticated using (public.is_workspace_member(workspace_id))
with check (public.is_workspace_member(workspace_id));

drop policy if exists workspace_notifications_member_read on public.workspace_notifications;
create policy workspace_notifications_member_read on public.workspace_notifications
for select to authenticated using (public.is_workspace_member(workspace_id));
drop policy if exists workspace_notifications_member_update on public.workspace_notifications;
create policy workspace_notifications_member_update on public.workspace_notifications
for update to authenticated using (public.is_workspace_member(workspace_id))
with check (public.is_workspace_member(workspace_id));

drop policy if exists products_services_member_access on public.products_services;
create policy products_services_member_access on public.products_services
for all to authenticated using (public.is_workspace_member(workspace_id))
with check (public.is_workspace_member(workspace_id));

drop policy if exists website_scan_runs_member_access on public.website_scan_runs;
create policy website_scan_runs_member_access on public.website_scan_runs
for all to authenticated using (public.is_workspace_member(workspace_id))
with check (public.is_workspace_member(workspace_id));

grant select, insert, update, delete on public.website_connections to authenticated;
grant select, update on public.human_requests to authenticated;
grant select, update on public.workspace_notifications to authenticated;
grant select, insert, update, delete on public.products_services to authenticated;
grant select, insert, update, delete on public.website_scan_runs to authenticated;
grant select, insert, update, delete on public.contacts to authenticated;
grant select, insert, update, delete on public.conversations to authenticated;
grant select, insert, update, delete on public.messages to authenticated;
grant select, insert, update, delete on public.knowledge_entries to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop trigger if exists update_website_connections_timestamp on public.website_connections;
create trigger update_website_connections_timestamp before update on public.website_connections
for each row execute function public.sync_updated_at();

drop trigger if exists update_products_services_timestamp on public.products_services;
create trigger update_products_services_timestamp before update on public.products_services
for each row execute function public.sync_updated_at();

commit;
